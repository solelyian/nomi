"""Generate design/tokens/tokens.css and Nomi.WinUI/Tokens.g.cs from tokens.json.

usage: python build.py           write both files
       python build.py --check   fail if they are stale or App.xaml colours differ from tokens.json
Mockups link tokens.css and the app compiles Tokens.g.cs, so both read the same values.
"""
import json, math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CSS = os.path.join(HERE, "tokens.css")
CS = os.path.join(ROOT, "Nomi.WinUI", "Tokens.g.cs")
APP = os.path.join(ROOT, "Nomi.WinUI", "App.xaml")

def css_colour(value):
    v = value.lstrip("#")
    if len(v) == 8:
        a, r, g, b = (int(v[i:i + 2], 16) for i in (0, 2, 4, 6))
        return f"rgba({r},{g},{b},{a / 255:.3f})"
    return "#" + v

def kebab(name):
    return re.sub(r"(?<!^)(?=[A-Z0-9])", "-", name.replace("Nomi", "", 1)).lower()

STEPS = 40

def spring(damping, response_ms):
    """Underdamped spring sampled into STEPS + 1 points: the mockup plays them with CSS linear(), the app with key frames."""
    w0 = 2 * math.pi / (response_ms / 1000)
    wd = w0 * math.sqrt(1 - damping ** 2)
    settle = math.log(500) / (damping * w0)
    points = []
    for i in range(STEPS + 1):
        t = settle * i / STEPS
        x = 1 - math.exp(-damping * w0 * t) * (math.cos(wd * t) + damping * w0 / wd * math.sin(wd * t))
        points.append(1.0 if i == STEPS else round(x, 4))
    return round(settle * 1000), points

def build_css(t):
    out = ["/* Generated by design/tokens/build.py from tokens.json. Do not edit. */"]
    for theme, selector in (("Light", ":root"), ("Default", "[data-theme=dark]")):
        values = ";".join(f"--{kebab(k)}:{css_colour(v)}" for k, v in t["themes"][theme].items())
        out.append(f"{selector}{{{values}}}")
    keys = ("title", "heading", "body", "small", "label", "icon", "pad", "gap", "radius", "rail", "aside", "bar")
    tiers = sorted(t["tiers"].items(), key=lambda kv: -kv[1]["minWidth"])
    for i, (name, tier) in enumerate(tiers):
        values = ";".join(f"--{k}:{tier[k]}px" for k in keys)
        if i == 0:
            out.append(f".shell{{{values}}}")
        else:
            out.append(f"@container win (max-width:{tiers[i - 1][1]['minWidth'] - 1}px){{.shell{{{values}}}}}")
    springs = []
    for name, s in t["springs"].items():
        ms, points = spring(s["dampingRatio"], s["responseMs"])
        curve = "linear(" + ",".join(f"{x:g}" for x in points) + ")"
        springs.append(f"--spring-{name.lower()}:{curve};--spring-{name.lower()}-ms:{ms}ms")
    p, r = t["press"], t["reveal"]
    springs.append(f"--press-small:{p['scaleSmall']};--press-large:{p['scaleLarge']};--press-large-from:{p['largeFrom']}px")
    springs.append(f"--reveal-offset:{r['offset']}px;--reveal-stagger:{r['staggerMs']}ms;--reveal-ms:{r['durationMs']}ms")
    out.append(":root{" + ";".join(springs) + "}")
    return "\n".join(out) + "\n"

def build_cs(t):
    lines = ["// Generated by design/tokens/build.py from design/tokens/tokens.json. Do not edit.",
             "namespace Nomi;", "", "public sealed record Spring(int DurationMs, float[] Curve);", "", "public sealed record Tier(string Name, double MinWidth, double Title, double Heading, double Body, double Small, double Label, double Icon, double Pad, double Gap, double Radius, double Rail, double Aside, double Bar, bool RailLabels, bool AsideDocked);",
             "", "public static class Tokens", "{"]
    tiers = sorted(t["tiers"].items(), key=lambda kv: -kv[1]["minWidth"])
    for name, v in tiers:
        args = ", ".join(str(v[k]) for k in ("minWidth", "title", "heading", "body", "small", "label", "icon", "pad", "gap", "radius", "rail", "aside", "bar"))
        lines.append(f"    public static readonly Tier {name} = new(\"{name}\", {args}, {str(v['railLabels']).lower()}, {str(v['asideDocked']).lower()});")
    lines.append("")
    lines.append("    public static Tier For(double width) => " + " : ".join(f"width >= {v['minWidth']} ? {n}" for n, v in tiers[:-1]) + f" : {tiers[-1][0]};")
    lines.append("")
    for name, s in t["springs"].items():
        ms, points = spring(s["dampingRatio"], s["responseMs"])
        lines.append(f"    public static readonly Spring {name}Spring = new({ms}, new[] {{ " + ", ".join(f"{x:g}f" for x in points) + " });")
    p, r = t["press"], t["reveal"]
    lines += ["", f"    public const float PressSmall = {p['scaleSmall']}f;", f"    public const float PressLarge = {p['scaleLarge']}f;",
              f"    public const double PressLargeFrom = {p['largeFrom']};", f"    public const float RevealOffset = {r['offset']}f;",
              f"    public const int RevealStaggerMs = {r['staggerMs']};", f"    public const int RevealMs = {r['durationMs']};", "}"]
    return "\n".join(lines) + "\n"

def app_mismatches(t):
    xaml = open(APP, encoding="utf-8-sig").read()
    problems = []
    for theme, colours in t["themes"].items():
        seg = xaml.split(f'<ResourceDictionary x:Key="{theme}">')[1].split("</ResourceDictionary>")[0]
        found = dict(re.findall(r'<SolidColorBrush x:Key="(Nomi\w+)" Color="(#[0-9A-Fa-f]+)"', seg))
        found.update(re.findall(r'<Color x:Key="(Nomi\w+)">(#[0-9A-Fa-f]+)<', seg))
        for key, value in colours.items():
            if found.get(key, "").upper() != value.upper():
                problems.append(f"{theme}.{key}: App.xaml has {found.get(key, 'nothing')}, tokens.json has {value}")
    return problems

def main():
    t = json.load(open(os.path.join(HERE, "tokens.json"), encoding="utf-8"))
    wanted = {CSS: build_css(t), CS: build_cs(t)}
    if "--check" in sys.argv:
        problems = [f"{os.path.relpath(p, ROOT)} is stale: run python design/tokens/build.py"
                    for p, text in wanted.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != text]
        problems += app_mismatches(t)
        for p in problems:
            print(p)
        sys.exit(1 if problems else 0)
    for p, text in wanted.items():
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("wrote", ", ".join(os.path.relpath(p, ROOT) for p in wanted))

if __name__ == "__main__":
    main()
